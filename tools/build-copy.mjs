// Builds js/copy-switch.js from tools/copy-blocks.json (the home page's original blocks, listed by
// tools/copy-collect.js) and tools/copy-new.json (the plain-language rewrite, keyed by block number).
// Each entry carries the start of the original text, so a rewrite is only ever applied to the block
// it was written for. Usage: node tools/build-copy.mjs
import { readFileSync, writeFileSync } from "node:fs";
const blocks = JSON.parse(readFileSync("tools/copy-blocks.json", "utf8")), next = JSON.parse(readFileSync("tools/copy-new.json", "utf8"));
const text = (h) => h.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&nbsp;/g, " ").replace(/\s+/g, "").slice(0, 64);
// Keyed by the start of the original text, not by position: scripts add and remove blocks as the page
// loads (the client-feedback counter, for one), so a position is not a stable address. A rewrite can only
// ever land on the block whose original wording it was written for.
const entries = {};
for (const [i, html] of Object.entries(next)) {
  const b = blocks[+i]; if (!b) throw new Error("no block " + i);
  const k = text(b.html); if (entries[k] !== undefined && entries[k] !== html) throw new Error(`two different rewrites share the opening "${k}"`);
  entries[k] = html;
}
for (const b of blocks) { const k = text(b.html); if (entries[k] !== undefined && next[b.i] === undefined) throw new Error(`block ${b.i} shares the opening "${k}" with a rewritten block but has no rewrite of its own`); }
const collect = readFileSync("tools/copy-collect.js", "utf8");
writeFileSync("js/copy-switch.js", `/* Home page copy switch. A TEST FEATURE.

   The page is served with Kakde Research's original V16 wording. This script
   shows a plain-language rewrite in its place (the same facts, written so a
   first-time reader and a finance professional can both follow it), and the
   "Switch copy" button at the foot of the page flips between the two. The
   choice is remembered on this device. Without script, the original shows.

   Generated by tools/build-copy.mjs from tools/copy-new.json. Do not edit by hand. */
(function () {
  'use strict';
${collect.replace(/^/gm, "  ").replace(/^\s*\/\*[\s\S]*?\*\/\n/, "")}
  var NEW = ${JSON.stringify(entries)};
  var KEY = 'kr-copy';
  var norm = function (s) { return s.replace(/\\s+/g, '').slice(0, 64); };
  var blocks = krCopyBlocks(document), pairs = [];
  for (var i = 0; i < blocks.length; i++) {
    var k = norm(blocks[i].textContent);
    if (Object.prototype.hasOwnProperty.call(NEW, k)) pairs.push({ el: blocks[i], original: blocks[i].innerHTML, plain: NEW[k] });
  }
  var mode = 'plain';
  try { if (window.localStorage.getItem(KEY) === 'original') mode = 'original'; } catch (_) {}
  var btn = document.querySelector('[data-copy-switch]'), state = document.querySelector('[data-copy-state]');
  function apply() {
    for (var i = 0; i < pairs.length; i++) pairs[i].el.innerHTML = mode === 'plain' ? pairs[i].plain : pairs[i].original;
    document.documentElement.setAttribute('data-copy', mode);
    if (state) state.textContent = mode === 'plain' ? 'Showing: plain-language copy' : 'Showing: original Kakde Research copy';
  }
  apply();
  if (btn) btn.addEventListener('click', function () {
    mode = mode === 'plain' ? 'original' : 'plain';
    try { window.localStorage.setItem(KEY, mode); } catch (_) {}
    apply();
  });
})();
`);
console.log(Object.keys(next).length, "blocks rewritten of", blocks.length, "(" + Object.keys(entries).length + " distinct openings)");
